import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { addDoc, collection, doc, getDoc, getDocs, getCountFromServer, query, orderBy, where, limit, setDoc, updateDoc, deleteDoc, serverTimestamp, deleteField, Timestamp } from 'firebase/firestore';
test('community posting, location revocation and moderation with two accounts', async () => {
 const env = await initializeTestEnvironment({projectId:'demo-smit-gym',firestore:{rules:readFileSync('firestore.rules','utf8')}});
 try {
 const a=env.authenticatedContext('audit-a').firestore(), b=env.authenticatedContext('audit-b').firestore(), anon=env.unauthenticatedContext().firestore();
 await assertSucceeds(setDoc(doc(a,'publicProfiles','audit-a'), {name:'Test A',geohash5:'sv8wr'}));
 assert.equal((await assertSucceeds(getDoc(doc(b,'publicProfiles','audit-a')))).data().geohash5,'sv8wr');
 await assertFails(getDoc(doc(anon,'publicProfiles','audit-a')));
 const areaQuery = query(collection(b,'publicProfiles'), where('geohash5','>=','sv8w'), where('geohash5','<','sv8w\uf8ff'));
 assert.equal((await assertSucceeds(getDocs(areaQuery))).size,1);
 await assertSucceeds(updateDoc(doc(a,'publicProfiles','audit-a'),{geohash5:deleteField()}));
 assert.equal((await assertSucceeds(getDocs(areaQuery))).size,0);
 const card = {area:'Example gym',activity:'Strength',availability:'Evenings',expiresAt:Timestamp.fromMillis(Date.now()+7*86400000)};
 await assertSucceeds(updateDoc(doc(a,'publicProfiles','audit-a'),{partnerCard:card}));
 const cardQuery = query(collection(b,'publicProfiles'), where('partnerCard.expiresAt','>',Timestamp.now()));
 assert.equal((await assertSucceeds(getDocs(cardQuery))).size,1);
 await assertSucceeds(updateDoc(doc(a,'publicProfiles','audit-a'),{partnerCard:deleteField()}));
 assert.equal((await assertSucceeds(getDocs(cardQuery))).size,0);
 const post=await assertSucceeds(addDoc(collection(a,'posts'),{uid:'audit-a',text:'Synthetic test',createdAt:serverTimestamp()}));
 assert.equal((await assertSucceeds(getDocs(query(collection(b,'posts'),orderBy('createdAt','desc'),limit(50))))).size,1);
 await assertFails(getDoc(doc(anon,'posts',post.id)));
 const like=doc(b,'posts',post.id,'likes','audit-b');
 await assertSucceeds(setDoc(like,{createdAt:serverTimestamp()}));
 assert.equal((await assertSucceeds(getCountFromServer(collection(a,'posts',post.id,'likes')))).data().count,1);
 await assertSucceeds(deleteDoc(like));
 const request=await assertSucceeds(addDoc(collection(a,'buddyRequests'),{fromUid:'audit-a',toUid:'audit-b',pairKey:'audit-a_audit-b',status:'pending'}));
 assert.equal((await assertSucceeds(getDocs(query(collection(b,'buddyRequests'),where('toUid','==','audit-b'),where('status','==','pending'))))).size,1);
 await assertFails(updateDoc(doc(a,'buddyRequests',request.id),{status:'accepted'}));
 await assertFails(updateDoc(doc(b,'buddyRequests',request.id),{status:'accepted',toName:'Changed'}));
 await assertSucceeds(updateDoc(doc(b,'buddyRequests',request.id),{status:'accepted'}));
 assert.equal((await assertSucceeds(getDoc(request))).data().status,'accepted');
 const block = doc(a,'communityBlocks','audit-a~audit-b');
 await assertSucceeds(setDoc(block,{ownerUid:'audit-a',targetUid:'audit-b'}));
 assert.equal((await assertSucceeds(getDocs(query(collection(b,'communityBlocks'),where('targetUid','==','audit-b'))))).size,1);
 await assertFails(getDoc(doc(b,'publicProfiles','audit-a')));
 await assertFails(addDoc(collection(b,'buddyRequests'),{fromUid:'audit-b',toUid:'audit-a',status:'pending'}));
 await assertFails(deleteDoc(doc(b,'communityBlocks','audit-a~audit-b')));
 await assertSucceeds(deleteDoc(block));
 await assertSucceeds(getDoc(doc(b,'publicProfiles','audit-a')));
 const report = doc(b,'communityReports','audit-b~audit-a');
 await assertSucceeds(setDoc(report,{reporterUid:'audit-b',targetUid:'audit-a',reason:'spam',createdAt:serverTimestamp()}));
 await assertFails(getDoc(report));
 await assertSucceeds(deleteDoc(post));
 } finally { await env.cleanup(); }
});
